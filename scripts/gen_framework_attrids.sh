#!/usr/bin/env bash
# Regenerate framework_attrids.txt: the android framework attr name -> resource ID
# map, used by gen_styleable.py to resolve framework (android:) attrs.
#
# Source: aapt2 dump of the SDK android.jar (public attrs). Private framework
# attrs (0x01120xxx, e.g. textEditSuggestionContainerLayout) are NOT emitted as
# resource declarations by aapt2 dump, so they are maintained by hand in the
# "Private framework attrs" section below — append new ones there as needed.
#
# Usage: bash scripts/gen_framework_attrids.sh [path/to/android.jar] [outfile]
set -euo pipefail
ANDROID_JAR="${1:-/opt/android-sdk/platforms/android-36/android.jar}"
OUT="${2:-scripts/framework_attrids.txt}"
AAPT2="${AAPT2:-$(ls /opt/android-sdk/build-tools/*/aapt2 2>/dev/null | sort -V | tail -1)}"

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

# Public attrs: "resource 0xID attr/NAME" -> "0xID NAME"
"$AAPT2" dump resources "$ANDROID_JAR" \
  | grep -oE 'resource 0x[0-9a-f]+ attr/[A-Za-z0-9_]+' \
  | sed 's#resource ##; s# attr/# #' \
  | sort -u > "$tmp"

{
  echo "# Framework attr name -> resource ID. GENERATED by gen_framework_attrids.sh"
  echo "# Source: aapt2 dump of \$(basename \"$ANDROID_JAR\"). Public attrs only from"
  echo "# the dump; private attrs (0x01120xxx) appended by hand below."
  echo "# Format: 0xID NAME   (one per line; # comments allowed)"
  echo ""
  cat "$tmp"
  echo ""
  echo "# --- Private framework attrs (not in aapt2 dump; maintained by hand) ---"
  echo "0x01120021 calendarViewMode"
  echo "0x01120109 textEditSuggestionContainerLayout"
  echo "0x0112010a textEditSuggestionHighlightStyle"
} > "$OUT"

echo "Wrote $OUT ($(wc -l < "$OUT") lines)"
